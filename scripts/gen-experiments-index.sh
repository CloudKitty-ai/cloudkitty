#!/usr/bin/env bash
# gen-experiments-index.sh [repo] — emit experiments/INDEX.md on stdout:
# every depth-1 experiments/ directory with the declaration and results
# files it carries (tracked files only; raws live in the native checkout
# by standing rule and are deliberately invisible here).
set -u
R=${1:-$(git rev-parse --show-toplevel)}
echo "# Experiments index"
echo
echo "Generated by \`scripts/gen-experiments-index.sh\` — do not edit by"
echo "hand; regenerate and commit (owning thread) when arcs change."
echo
echo "| arc | declaration | results |"
echo "|---|---|---|"
git -C "$R" ls-files 'experiments/*/*' | cut -d/ -f2 | LC_ALL=C sort -u | while IFS= read -r d; do
  pre=$(git -C "$R" ls-files "experiments/$d/*" | awk -F/ 'tolower($3) ~ /^(prereg|declaration)/ {print $3}' | LC_ALL=C sort | tr '\n' ' ')
  res=$(git -C "$R" ls-files "experiments/$d/*" | awk -F/ 'tolower($3) ~ /^results/ {print $3}' | LC_ALL=C sort | tr '\n' ' ')
  pre=${pre% }; res=${res% }
  echo "| \`$d\` | ${pre:-—} | ${res:-—} |"
done
